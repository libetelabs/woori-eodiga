def write_cell(cell, text):
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    first = True
    for line in text.split("\n"):
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        head = line.startswith("## ")
        r = p.add_run(line[3:] if head else line)
        r.bold = head
        r.font.size = Pt(10)


def fill_line(p, label, value):
    """'라벨: ____' 문단을 '라벨: 값' 으로. 첫 run 서식을 남긴다."""
    lead = "\n" if p.text.startswith("\n") else ""
    for r in p.runs[1:]:
        r._element.getparent().remove(r._element)
    p.runs[0].text = f"{lead}{label}: {value}"


